"""Generate supported single-reducer mechanisms and explicit wrist-axis alternatives."""
import json
import xml.etree.ElementTree as ET
import numpy as np
import mujoco
from armsim.catalog import (GEAR_COLOR, MOTOR_COLOR, BELT_COLOR,
                           LAYOUTS, LINKS, MODEL_DIR, URDF_PATH, Layout, WRIST_PROFILES, axes_for)
from armsim.model_primitives import add, values, rpy_quaternion
from armsim.mechanics import build_mechanics

def layout_reference(layout, source, wrist_profile="reference"):
    """A private copy of the corrected source URDF for each layout/profile."""
    reference = ET.fromstring(ET.tostring(source))
    axes = axes_for(wrist_profile)
    index = 0
    for joint in reference.findall("joint"):
        if joint.attrib["type"] == "revolute":
            joint.find("axis").set("xyz", values(axes[index]))
            index += 1
    if not layout.short_l2:
        return reference
    for joint in reference.findall("joint"):
        if joint.attrib["name"] == "joint_4":
            joint.find("origin").set("xyz", values([0, 0, layout.l2_length]))
            if layout.perpendicular_j4:
                joint.find('origin').set('rpy',values([-np.pi/2,0,0]))
        elif joint.attrib["name"] == "joint_5":
            joint.find("origin").set("xyz", values([0, 0, layout.l3_length]))
    # Preserve the original combined L2+L3 structural mass of 2.4 kg and
    # distribute it over the revised lengths. Recompute COM and box inertias.
    linear_mass = 2.4 / (layout.l2_length + layout.l3_length)
    for link in reference.findall("link"):
        if link.attrib["name"] not in ("forearm_link", "wrist_1_link"):
            continue
        length = layout.l2_length if link.attrib["name"] == "forearm_link" else layout.l3_length
        mass = linear_mass * length
        x, y = 0.06, 0.06
        inertial = link.find("inertial")
        inertial.find("origin").set("xyz", values([0, 0, length / 2]))
        inertial.find("mass").set("value", values([mass]))
        diagonal = mass / 12 * np.array([y*y + length*length, x*x + length*length, x*x + y*y])
        inertia = inertial.find("inertia")
        for key, value in zip(("ixx", "iyy", "izz"), diagonal):
            inertia.set(key, values([value]))
        for tag in ("visual", "collision"):
            element = link.find(tag)
            element.find("origin").set("xyz", values([0, 0, length / 2]))
            geometry = element.find("geometry")
            geometry.clear()
            add(geometry, "box", size=values([x, y, length]))
    return reference


def generate(layout: Layout, urdf, wrist_profile="reference"):
    urdf = layout_reference(layout, urdf, wrist_profile)
    axes = axes_for(wrist_profile)
    output_path = layout.path_for(wrist_profile)
    root = ET.Element("mujoco", model=f"{layout.number}-base-6dof | {layout.title} | {wrist_profile}")
    root.append(ET.Comment("Generated by python -m armsim.generate_models; edit the generator to regenerate. SI units, angles in radians."))
    root.append(ET.Comment("Parallel-shaft local drives only. All stages use reducers; rigid ideal transmission with reflected rotor inertia."))
    add(root, "compiler", angle="radian", autolimits="true", inertiafromgeom="auto", fusestatic="false")
    add(root, "option", timestep="0.002", integrator="implicitfast", gravity="0 0 -9.81")
    visual = add(root, "visual")
    add(visual, "global", offwidth="1600", offheight="1200")
    add(visual, "quality", shadowsize="1024", numslices="20", numstacks="8", numquads="2")
    add(visual, "headlight", ambient="0.4 0.4 0.4", diffuse="0.6 0.6 0.6")
    add(root, "statistic", center="0 0 0.5", extent="1.4")
    custom = add(root, "custom")
    add(custom, "text", name="layout_title", data=layout.title)
    add(custom, "text", name="layout_description", data=layout.description)
    add(custom, 'text', name='j4_mount', data=layout.j4_mount)
    add(custom, "text", name="geometry_family", data="short_l2_extended_l3" if layout.short_l2 else "long_l2")
    add(custom, "numeric", name="link_lengths_L1_L2_L3", data=values([0.32, layout.l2_length, layout.l3_length]))
    add(custom, "text", name="transmission_model", data="Coaxial reducers and local 1:1 parallel-shaft belts. No axis-redirection gears or paths crossing joints. Belt stiffness and tooth contact are not simulated.")
    asset = add(root, "asset")
    add(asset, "texture", name="floor_texture", type="2d", builtin="checker", rgb1="0.13 0.16 0.21", rgb2="0.18 0.22 0.28", width="256", height="256")
    add(asset, "material", name="floor_material", texture="floor_texture", texrepeat="8 8", reflectance="0.08")
    for name, color in (("motor_teal", MOTOR_COLOR), ("gearbox_amber", GEAR_COLOR),
                        ("belt_purple", BELT_COLOR), ("shaft_metal", (0.62, 0.67, 0.74, 1)),
                        ("bracket_dark", (0.16, 0.20, 0.27, 1))):
        add(asset, "material", name=name, rgba=values(color), shininess="0.45", specular="0.35")
    for material in urdf.findall("material"):
        add(asset, "material", name=material.attrib["name"], rgba=material.find("color").attrib["rgba"])
    world = add(root, "worldbody")
    add(world, "light", pos="1 -2 3", dir="-0.3 0.5 -1", directional="true", diffuse="0.8 0.8 0.8")
    add(world, "geom", name="ground", type="plane", size="2 2 0.1", material="floor_material", group="5")
    add(world, "site", name="world_frame", pos="0 0 0.001", size="0.003", rgba="1 1 1 0")
    base = add(world, "body", name="base_link")
    bodies = {"base_link": base}
    urdf_links = {link.attrib["name"]: link for link in urdf.findall("link")}
    urdf_joints = urdf.findall("joint")
    output_joints = []
    for source in urdf_joints:
        parent_name = source.find("parent").attrib["link"]
        child_name = source.find("child").attrib["link"]
        origin=source.find('origin').attrib
        body = add(bodies[parent_name], "body", name=child_name, pos=origin['xyz'],
                   quat=values(rpy_quaternion(np.fromstring(origin.get('rpy','0 0 0'),sep=' '))))
        bodies[child_name] = body
        if source.attrib["type"] != "fixed":
            limit = source.find("limit").attrib
            dynamics = source.find("dynamics").attrib
            joint = add(body, "joint", name=source.attrib["name"], type="hinge", axis=source.find("axis").attrib["xyz"],
                        range=f"{limit['lower']} {limit['upper']}", damping=dynamics["damping"], frictionloss=dynamics["friction"])
            output_joints.append(joint)
            add(body, "site", name=f"J{len(output_joints)}", size="0.004", rgba="1 1 1 0")
    add(bodies["tool0"], "site", name="tool_frame", size="0.007", rgba="1 0.5 0.1 1", group="4")
    metadata = build_mechanics(layout, bodies, axes)
    for joint, drive in zip(output_joints, metadata):
        joint.set("armature", values([drive["reflected_armature_kg_m2"]]))
    actuators = add(root, "actuator")
    # Motor coordinate u=N*q. F_motor=tau_out/N. kp_motor=kp_out/N^2.
    gains = [180, 240, 180, 70, 55, 40]
    damping = [20, 25, 18, 5, 4, 3]
    for index, (source, drive) in enumerate(zip([j for j in urdf_joints if j.attrib["type"] != "fixed"], metadata)):
        ratio = drive["ratio"]
        limit = source.find("limit").attrib
        effort = float(limit["effort"])
        add(actuators, "position", name=f"M{index + 1}_servo", joint=source.attrib["name"], gear=ratio,
            kp=gains[index] / ratio ** 2, kv=damping[index] / ratio ** 2,
            ctrlrange=values(np.array([float(limit["lower"]), float(limit["upper"])]) * ratio),
            forcerange=values([-effort / ratio, effort / ratio]))
    sensors = add(root, "sensor")
    add(sensors, "framepos", name="tool_position", objtype="site", objname="tool_frame")
    add(sensors, "framequat", name="tool_orientation", objtype="site", objname="tool_frame")
    keyframes = add(root, "keyframe")
    add(keyframes, "key", name="zero", qpos="0 0 0 0 0 0", ctrl="0 0 0 0 0 0")
    inspect_pose=layout.bent_pose
    add(keyframes, "key", name="inspect", qpos=values(inspect_pose), ctrl=values(inspect_pose * layout.ratios))
    ET.indent(root, space="  ")
    output_path.write_text('<?xml version="1.0" encoding="utf-8"?>\n' + ET.tostring(root, encoding="unicode") + "\n", encoding="utf-8")
    model = mujoco.MjModel.from_xml_path(str(output_path))
    data = mujoco.MjData(model)
    mujoco.mj_forward(model, data)
    hardware = [model.body(f"{kind}_{j}").id for kind in ("motor", "gearbox") for j in range(1,7)]
    weights = model.body_mass[hardware]
    offsets_x = data.xipos[hardware, 0]
    data.qpos[:] = inspect_pose
    mujoco.mj_forward(model, data)
    matrix = np.empty((6,6))
    mujoco.mj_fullM(model, data, matrix)
    jacp,jacr = np.zeros((3,6)),np.zeros((3,6))
    mujoco.mj_jacBody(model,data,jacp,jacr,model.body("tool0").id)
    rank = int(np.linalg.matrix_rank(np.vstack((jacp,jacr)),tol=1e-8))
    if rank != 6:
        raise ValueError(f'{layout.title} / {wrist_profile} lacks six independent tool motions at the inspection pose')
    return {"wrist_profile": wrist_profile, "wrist_label": WRIST_PROFILES[wrist_profile][0],
            "joint_axes": axes.tolist(), "tool_rank_inspect": rank, "geometry_count": model.ngeom,
            "inspect_pose_radians": inspect_pose.tolist(),
            "structural_inertia_model": "aluminium edge volume at 2700 kg/m3; explicit motor/reducer component estimates",
            "number": layout.number, "title": layout.title, "file": output_path.name,
            "description": layout.description, "drives": metadata,
            "j4_mount": layout.j4_mount,
            "j4_location": "short_l2_coupling" if layout.short_l2 else "end_of_link_2",
            "geometry_family": "short_l2_extended_l3" if layout.short_l2 else "long_l2",
            "preserves_urdf_geometry": not layout.short_l2 and wrist_profile=='reference',
            "preserves_urdf_joint_origins": not layout.short_l2,
            "link_lengths_m": {"L1": 0.32, "L2": layout.l2_length, "L3": layout.l3_length},
            "home_hardware_com_x_mm": float(np.average(offsets_x, weights=weights) * 1000),
            "max_home_hardware_center_x_mm": float(np.max(np.abs(offsets_x)) * 1000),
            "joint2_locked_inertia_inspect_kg_m2": float(matrix[1,1]),
            "joint3_locked_inertia_inspect_kg_m2": float(matrix[2,2])}


def main():
    source = ET.parse(URDF_PATH).getroot()
    # Retire previous transverse-J4 profiles; active models must roll L3.
    obsolete = [MODEL_DIR / f'{layout.number}-base-6dof-{profile}.xml'
                for layout in LAYOUTS for profile in ('j4x-j6y','j4y-j6x','j4z-j6x')]
    obsolete.extend(MODEL_DIR / f'base-6dof-{profile}.urdf' for profile in ('j4x-j6y','j4y-j6x','j4z-j6x'))
    for path in obsolete:
        path.unlink(missing_ok=True)
    manifest = [generate(layout, source, profile) for layout in LAYOUTS for profile in WRIST_PROFILES]
    (MODEL_DIR / "layouts.json").write_text(json.dumps(manifest,indent=2)+"\n",encoding="utf-8")
    for profile in WRIST_PROFILES:
        if profile == "reference": continue
        tree = layout_reference(LAYOUTS[0],source,profile)
        tree.set("name",f"base-6dof-{profile}")
        ET.indent(tree,space="  ")
        (MODEL_DIR / f"base-6dof-{profile}.urdf").write_text(
            '<?xml version="1.0" encoding="utf-8"?>\n'+ET.tostring(tree,encoding="unicode")+'\n',encoding="utf-8")
    tree=layout_reference(LAYOUTS[6],source)
    tree.set('name','base-6dof-perpendicular-j4')
    ET.indent(tree,space='  ')
    (MODEL_DIR/'base-6dof-perpendicular-j4.urdf').write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n'+ET.tostring(tree,encoding='unicode')+'\n',encoding='utf-8')
    for item in manifest:
        print(f"Created {item['file']} | tool Jacobian rank {item['tool_rank_inspect']}/6")

if __name__ == "__main__":
    main()
